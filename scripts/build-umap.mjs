import { build } from "esbuild";
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";

const result = await build({
  stdin: {
    contents: 'export { UMAP } from "umap-js";',
    resolveDir: process.cwd(),
    sourcefile: "umap-entry.mjs",
  },
  bundle: true,
  format: "esm",
  platform: "browser",
  minify: true,
  outfile: "vendor/umap.mjs",
  legalComments: "eof",
  metafile: true,
  banner: { js: "// Generated by npm run build:vendor. See umap.LICENSE.txt for third-party licenses." },
});

const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.startsWith("node_modules/")) continue;
  let directory = dirname(resolve(input));
  while (!existsSync(join(directory, "package.json"))) directory = dirname(directory);
  packages.add(directory);
}
const licenses = [];
for (const directory of [...packages].sort()) {
  const { name, version } = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
  const license = await readFile(join(directory, "LICENSE"), "utf8");
  licenses.push(`${name}@${version}\n\n${license}`);
}
await writeFile("vendor/umap.LICENSE.txt", licenses.join("\n\n--------------------\n\n"));
